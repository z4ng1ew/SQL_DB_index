-- ВОПРОС: Как работает EXCEPT?
-- ОТВЕТ: 
-- 1. Выполняет первый SELECT → получает множество A (все даты января)
-- 2. Выполняет второй SELECT → получает множество B (даты посещений)
-- 3. Вычитает B из A → оставляет только элементы из A, которых нет в B
-- 4. Удаляет дубликаты (если есть)
-- 5. Возвращает результат

-- ВОПРОС: Почему не используется NOT IN или NOT EXISTS?
-- ОТВЕТ: EXCEPT - это более декларативный и читаемый подход.
-- Альтернативы (дают тот же результат):
-- 
-- 1) С NOT IN:
--    SELECT generated_date AS missing_date
--    FROM v_generated_dates
--    WHERE generated_date NOT IN (SELECT visit_date FROM person_visits)
--    ORDER BY missing_date;
-- 
-- 2) С NOT EXISTS:
--    SELECT generated_date AS missing_date
--    FROM v_generated_dates vgd
--    WHERE NOT EXISTS (
--        SELECT 1 FROM person_visits pv 
--        WHERE pv.visit_date = vgd.generated_date
--    )
--    ORDER BY missing_date;
-- 
-- Но EXCEPT короче и яснее показывает операцию над множествами.

-- ВОПРОС: Что будет, если в person_visits есть дубликаты дат?
-- ОТВЕТ: EXCEPT автоматически убирает дубликаты из ОБОИХ множеств.
-- Например:
-- person_visits содержит:
--   2022-01-01 (2 раза - два человека пришли в этот день)
--   2022-01-02 (3 раза - три посещения)
-- 
-- EXCEPT превратит это в уникальные даты:
--   {2022-01-01, 2022-01-02}
-- 
-- И вычтет из всех дат января. В результате эти даты не попадут
-- в missing_date (потому что были посещения).

-- ВОПРОС: Нужно ли фильтровать person_visits по январю 2022?
-- ОТВЕТ: НЕТ, не обязательно!
-- Причина: EXCEPT работает так:
-- 
-- A EXCEPT B = только те элементы из A, которых нет в B
-- 
-- Если в person_visits есть дата '2022-02-15' (февраль),
-- её нет в v_generated_dates (только январь),
-- поэтому она никак не повлияет на результат.
-- 
-- Но можно добавить фильтр для оптимизации:
-- SELECT visit_date FROM person_visits 
-- WHERE visit_date BETWEEN '2022-01-01' AND '2022-01-31'
-- 
-- Это ускорит запрос на больших данных, но логика не изменится.

-- ВОПРОС: Что такое "операция над множествами"?
-- ОТВЕТ: Это операции из теории множеств:
-- - UNION (объединение): A ∪ B - все элементы из A и B
-- - INTERSECT (пересечение): A ∩ B - элементы, которые есть И в A, И в B
-- - EXCEPT (разность): A \ B - элементы из A, которых НЕТ в B
-- 
-- В SQL все три операции доступны.

-- ВОПРОС: Сколько строк вернёт этот запрос?
-- ОТВЕТ: Зависит от данных в person_visits.
-- 
-- Расчёт:
-- - Всего дней в январе: 31
-- - Дней с посещениями: COUNT(DISTINCT visit_date FROM person_visits WHERE ...)
-- - Пропущенных дней: 31 - количество_дней_с_посещениями
-- 
-- Например, в тестовых данных model.sql:
-- Посещения были: 01, 02, 03, 04, 05, 06, 07, 08, 09, 10 января (10 дней)
-- Пропущенные: 11-31 января (21 день)
-- Результат: 21 строка

