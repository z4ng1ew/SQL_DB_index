FROM v_generated_dates


-- =============================================================================
-- Оператор разности множеств
-- =============================================================================

-- EXCEPT - оператор теории множеств (вычитание множеств)
-- Синтаксис: A EXCEPT B
-- Результат: все элементы из A, которых НЕТ в B
-- 
-- Математическая запись: A \ B (A минус B)
-- 
-- ВАЖНО: EXCEPT автоматически удаляет дубликаты (как UNION)
-- Альтернатива: EXCEPT ALL - оставляет дубликаты
-- 
-- Примеры работы EXCEPT:
-- {1, 2, 3} EXCEPT {2, 4} = {1, 3}
-- {Anna, Bob} EXCEPT {Bob, Kate} = {Anna}
-- 
-- В нашем случае:
-- {все_даты_января} EXCEPT {даты_посещений} = {даты_без_посещений}
