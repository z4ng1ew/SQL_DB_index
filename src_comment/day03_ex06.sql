-- ВОПРОС: Чем MATERIALIZED VIEW отличается от обычного VIEW?
-- ОТВЕТ:
-- 
-- VIEW (обычное представление):
-- - Хранит только SQL-запрос (текст)
-- - При SELECT выполняет запрос заново к таблицам
-- - Всегда показывает АКТУАЛЬНЫЕ данные
-- - НЕ занимает место на диске (кроме определения)
-- - Медленнее (каждый раз пересчитывает)
-- 
-- MATERIALIZED VIEW (материализованное):
-- - Хранит SQL-запрос И результат его выполнения
-- - При SELECT читает СОХРАНЁННЫЕ данные с диска
-- - Показывает данные с ЗАДЕРЖКОЙ (до REFRESH)
-- - ЗАНИМАЕТ место на диске (как таблица)
-- - Быстрее (данные уже готовы)
-- 
-- Аналогия:
-- VIEW = функция (вызывается каждый раз)
-- MVIEW = переменная с кэшем (вычислили один раз, используем много раз)

-- ВОПРОС: Почему нельзя использовать CREATE OR REPLACE для MVIEW?
-- ОТВЕТ: Особенности реализации PostgreSQL.
-- 
-- Для VIEW:
-- CREATE OR REPLACE VIEW ... ✅ работает
-- 
-- Для MVIEW:
-- CREATE OR REPLACE MATERIALIZED VIEW ... ❌ синтаксическая ошибка!
-- 
-- Причина: MVIEW содержит физические данные на диске
-- Замена может быть опасной (потеря данных, индексов)
-- PostgreSQL требует явного DROP перед CREATE
-- 
-- Правильный подход:
-- DROP MATERIALIZED VIEW IF EXISTS mv_name;
-- CREATE MATERIALIZED VIEW mv_name AS ...;

-- ВОПРОС: Как работает цепочка JOIN'ов?
-- ОТВЕТ: Пошаговое выполнение:
-- 
-- Шаг 1: menu
-- ┌────┬─────────────┬───────────────┬───────┐
-- │ id │ pizzeria_id │ pizza_name    │ price │
-- ├────┼─────────────┼───────────────┼───────┤
-- │ 12 │     4       │ cheese pizza  │  700  │ ← подходит (< 800)
-- │ 14 │     4       │ pepperoni     │ 1000  │ ← НЕ подходит
-- └────┴─────────────┴───────────────┴───────┘
-- 
-- Шаг 2: JOIN pizzeria (menu → pizzeria)
-- ┌────┬─────────────┬───────────────┬───────┬─────────────┐
-- │ id │ pizzeria_id │ pizza_name    │ price │ pizzeria    │
-- ├────┼─────────────┼───────────────┼───────┼─────────────┤
-- │ 12 │     4       │ cheese pizza  │  700  │ Papa Johns  │
-- └────┴─────────────┴───────────────┴───────┴─────────────┘
-- 
-- Шаг 3: JOIN person_visits (+ посещения)
-- ┌────┬───────┬─────────────┬────────────┬───────────┐
-- │... │ price │ pizzeria    │ person_id  │visit_date │
-- ├────┼───────┼─────────────┼────────────┼───────────┤
-- │... │  700  │ Papa Johns  │     9      │2022-01-08 │
-- └────┴───────┴─────────────┴────────────┴───────────┘
-- 
-- Шаг 4: JOIN person (+ имена людей)
-- ┌───────┬─────────────┬──────────┬────────────┐
-- │ price │ pizzeria    │ name     │visit_date  │
-- ├───────┼─────────────┼──────────┼────────────┤
-- │  700  │ Papa Johns  │ Dmitriy  │2022-01-08  │
-- └───────┴─────────────┴──────────┴────────────┘
-- 
-- Шаг 5: WHERE фильтрация
-- price < 800 ✅ (700 < 800)
-- name = 'Dmitriy' ✅
-- visit_date = '2022-01-08' ✅
-- 
-- Финальный результат:
-- ┌─────────────┐
-- │ pizzeria    │
-- ├─────────────┤
-- │ Papa Johns  │
-- └─────────────┘

-- ВОПРОС: Что означает "мог съесть"?
-- ОТВЕТ: Задание НЕ требует проверки реального заказа!
-- 
-- Проверяем:
-- ✅ Человек БЫЛ в пиццерии (есть запись в person_visits)
-- ✅ В пиццерии ЕСТЬ пицца < 800₽ (есть в menu)
-- 
-- НЕ проверяем:
-- ❌ Делал ли человек заказ (НЕ смотрим person_order)
-- ❌ Какую именно пиццу заказал
-- 
-- Логика: если человек был в пиццерии, где есть дешёвая пицца,
-- он ТЕОРЕТИЧЕСКИ МОГ её съесть (была возможность).

-- ВОПРОС: Почему начинаем с menu, а не с person_visits?
-- ОТВЕТ: Можно начать с любой таблицы, результат будет одинаковый.
-- 
-- Вариант 1 (как в коде):
-- FROM menu → JOIN pizzeria → JOIN person_visits → JOIN person
-- 
-- Вариант 2 (альтернатива):
-- FROM person_visits → JOIN person → JOIN menu → JOIN pizzeria
-- 
-- Вариант 3 (ещё один):
-- FROM person → JOIN person_visits → JOIN menu → JOIN pizzeria
-- 
-- При INNER JOIN порядок не важен для корректности!
-- Но для читаемости логичнее:
-- - Начать с той таблицы, которую сильнее фильтруем (menu - price < 800)
-- - Или с центральной таблицы (person_visits - связывает всё)

-- ВОПРОС: Сколько данных хранит MATERIALIZED VIEW?
-- ОТВЕТ: MVIEW сохраняет результат SELECT на диске.
-- 
-- В нашем случае:
-- - 1 строка (Papa Johns)
-- - 1 колонка VARCHAR (название пиццерии)
-- - Размер: ~50-100 байт
-- 
-- Проверка размера:
-- SELECT pg_size_pretty(pg_total_relation_size('mv_dmitriy_visits_and_eats'));
-- 
-- Сравнение:
-- - Обычный VIEW: ~0 байт (только SQL-текст в pg_views)
-- - MVIEW: реальные данные + индексы (если есть)

-- ВОПРОС: Когда использовать MVIEW, а когда VIEW?
-- ОТВЕТ:
-- 
-- Используй MATERIALIZED VIEW если:
-- ✅ Запрос медленный (сложные JOIN, агрегации)
-- ✅ Данные меняются редко
-- ✅ Можно потерпеть небольшую задержку актуальности
-- ✅ Один и тот же результат запрашивается часто
-- 
-- Используй обычный VIEW если:
-- ✅ Данные меняются часто
-- ✅ Нужна 100% актуальность
-- ✅ Запрос быстрый
-- ✅ Запрос делается редко
-- 
-- Пример:
-- - Отчёт по продажам за месяц → MVIEW (пересчитываем раз в час)
-- - Текущий баланс счёта → VIEW (должен быть актуальным)

-- =============================================================================
```

