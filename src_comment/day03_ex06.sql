### Вопрос 1: "Как обновить данные в MATERIALIZED VIEW?"

**Ответ:**

```sql
-- Команда обновления:
REFRESH MATERIALIZED VIEW mv_dmitriy_visits_and_eats;

-- Что происходит:
-- 1. PostgreSQL выполняет сохранённый SELECT заново
-- 2. Удаляет старые данные из MVIEW
-- 3. Записывает новые данные на диск
-- 4. MVIEW теперь актуален

-- Когда нужно REFRESH?
-- - После изменений в базовых таблицах (person, menu, person_visits)
-- - По расписанию (например, каждый час через cron)
-- - Вручную, когда нужны свежие данные

-- Варианты REFRESH:
REFRESH MATERIALIZED VIEW mv_name;  -- обычное обновление
REFRESH MATERIALIZED VIEW CONCURRENTLY mv_name;  -- без блокировки
```

