### Вопрос 6: "Зачем использовать MVIEW для такого простого запроса?"

**Ответ:**

```
В реальной жизни MVIEW используют для СЛОЖНЫХ запросов.

Наш запрос простой (учебный пример), но представь:

Реальный сценарий:
- Таблица person_visits: 10 миллионов строк
- Таблица person_order: 50 миллионов строк
- Таблица menu: 100 000 строк
- Сложная аналитика с агрегациями

Запрос выполняется 30 секунд каждый раз!

С MATERIALIZED VIEW:
1. CREATE MVIEW: выполнился 1 раз за 30 секунд
2. SELECT FROM MVIEW: выполняется за 0.001 секунды!
3. REFRESH раз в час: 30 секунд раз в час

Вместо 30 секунд на каждый запрос → мгновенный ответ!

Примеры использования:
- Дашборды аналитики (обновление раз в 15 минут)
- Отчёты (пересчёт ночью)
- Сложные JOIN'ы для API (кэширование результата)
- Агрегации больших данных

В нашем учебном примере это избыточно,
но принцип тот же!
```

