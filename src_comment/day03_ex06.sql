### Вопрос 4: "Почему JOIN по pizzeria_id, а не по конкретной пицце?"

**Ответ:**

```
Задание требует: "МОГ съесть пиццу дешевле 800₽"

Это НЕ означает "заказал конкретную пиццу"!

Логика:
1. Dmitriy был в пиццерии X
2. В пиццерии X ЕСТЬ пицца < 800₽
3. Значит, он МОГ её заказать

Мы НЕ проверяем:
❌ Заказывал ли он вообще (таблица person_order)
❌ Какую именно пиццу заказал
❌ Съел ли он её

Проверяем только ВОЗМОЖНОСТЬ:
✅ Был в пиццерии
✅ Там была доступна дешёвая пицца

JOIN по pizzeria_id корректен:
- menu.pizzeria_id = 4 (Papa Johns)
- person_visits.pizzeria_id = 4 (Papa Johns)
- Dmitriy был в той же пиццерии, где есть дешёвая пицца!

Если бы JOIN был по конкретной пицце (menu.id),
это означало бы "заказал ЭТУ пиццу", но у нас нет такой информации
(для этого нужна таблица person_order, которую мы НЕ используем).
```

