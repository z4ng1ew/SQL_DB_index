### Вопрос 2: "Можно ли создать индекс на MATERIALIZED VIEW?"

**Ответ:**

```sql
ДА! Это одно из преимуществ MVIEW над обычным VIEW.

-- Создание индекса:
CREATE INDEX idx_pizzeria_name 
ON mv_dmitriy_visits_and_eats(pizzeria_name);

-- Теперь поиск ещё быстрее:
SELECT * FROM mv_dmitriy_visits_and_eats 
WHERE pizzeria_name = 'Papa Johns';
-- Использует индекс → очень быстро!

-- На обычном VIEW индекс создать НЕЛЬЗЯ:
CREATE INDEX idx ON v_persons_female(name);
-- ERROR: cannot create index on view

Поэтому MVIEW используют для оптимизации производительности.
```

