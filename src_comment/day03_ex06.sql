### Вопрос 5: "Что будет, если данные изменятся?"

**Ответ:**

```sql
Сценарий:
1. Создали MVIEW (результат: Papa Johns)
2. Добавили новое посещение:
   INSERT INTO person_visits 
   VALUES (100, 9, 3, '2022-01-08');
   -- Dmitriy теперь был ещё и в DoDo Pizza (id=3)

3. В DoDo Pizza есть cheese pizza за 780₽ (< 800):
   menu: id=10, pizzeria_id=3, price=780

4. Запрашиваем MVIEW:
   SELECT * FROM mv_dmitriy_visits_and_eats;
   
   Результат: ┌───────────────┐
              │ Papa Johns    │ ← СТАРЫЕ данные!
              └───────────────┘
   
   DoDo Pizza НЕ появилась! Почему?

Потому что MATERIALIZED VIEW хранит данные,
которые были на момент CREATE (или последнего REFRESH).

Чтобы увидеть изменения:
REFRESH MATERIALIZED VIEW mv_dmitriy_visits_and_eats;

Теперь:
SELECT * FROM mv_dmitriy_visits_and_eats;

Результат: ┌───────────────┐
           │ DoDo Pizza    │ ← новые данные
           │ Papa Johns    │
           └───────────────┘

Это ключевое отличие MVIEW от VIEW!
VIEW показал бы изменения сразу.
```

