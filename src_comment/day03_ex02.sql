### Вопрос 4: "Почему COUNT(*) = 31, а не просто COUNT(*)?"

**Ответ:**
```
COUNT(*) = 31 - это ВЫРАЖЕНИЕ, которое возвращает BOOLEAN.

COUNT(*) - подсчитывает строки, возвращает число (31)
= 31 - сравнивает с ожидаемым значением
Результат: true или false

Это проверка корректности:
