### Вопрос 1: "Что такое generate_series?"

**Ответ:**
```
generate_series - это встроенная функция PostgreSQL, которая 
генерирует последовательность значений.

Синтаксис:
generate_series(start, stop, step)

Типы данных:
- Числа: generate_series(1, 10, 1) → 1, 2, 3, ..., 10
- Даты: generate_series('2022-01-01', '2022-01-31', '1 day')
- Timestamps: generate_series(timestamp '2022-01-01', ...)

Это set-returning function (SRF) - возвращает набор строк,
а не одно значение.
```

