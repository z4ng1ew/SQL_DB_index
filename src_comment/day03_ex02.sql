### 2. `g::date` - приведение типа

**Синтаксис:**
```sql
значение::тип
```

**Расшифровка:**
- **g** = результат из `generate_series` (тип TIMESTAMP)
- **::date** = "преобразовать в DATE" (оператор приведения типа)

**Примеры:**

```sql
-- TIMESTAMP → DATE
'2022-01-15 14:30:00'::date  → '2022-01-15'

-- Текст → число
'123'::integer  → 123

-- Число → текст
123::text  → '123'
```

**Аналогия на JavaScript:**

```javascript
// В JS это как приведение типа:
const timestamp = new Date('2022-01-15T14:30:00');
const dateOnly = timestamp.toISOString().split('T')[0];
// '2022-01-15'
```

**На C:**

```c
// Приведение типа в C:
float x = 3.14;
int y = (int)x;  // y = 3
```

