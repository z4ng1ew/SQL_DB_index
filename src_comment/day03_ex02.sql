### Вопрос 3: "Что такое INTERVAL?"

**Ответ:**
```
INTERVAL - это тип данных для временных интервалов.

Примеры:
INTERVAL '1 day'      - один день
INTERVAL '2 hours'    - два часа
INTERVAL '30 minutes' - 30 минут
INTERVAL '1 week'     - одна неделя
INTERVAL '3 months'   - три месяца
INTERVAL '1 year'     - один год

Можно комбинировать:
INTERVAL '1 day 2 hours 30 minutes'

Используется для:
- Арифметики с датами: '2022-01-01'::date + INTERVAL '1 day'
- generate_series (как в нашем случае)
- Вычислений разницы во времени
```

