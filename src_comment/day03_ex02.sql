## 🐛 В чём проблема?

### ❌ Твой код (с ошибкой):

```sql
create view v_generated_dates as
select g::date as generated_date
from generate_series('2022-01-01','2022-01-31',interval '1 day') as g
order by 1  -- ← ВОТ ПРОБЛЕМА!
```

### 🚫 Почему не работает?

**В PostgreSQL НЕЛЬЗЯ использовать `ORDER BY` внутри определения VIEW!**

**Расшифровка:**
- VIEW - это просто "сохранённый SELECT"
- VIEW не хранит данные в определённом порядке
- Сортировка делается **при запросе к VIEW**, а не внутри VIEW

