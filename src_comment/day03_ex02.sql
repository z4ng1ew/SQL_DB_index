### Вопрос 2: "Чем :: отличается от CAST?"

**Ответ:**
```sql
-- Оператор :: (PostgreSQL-специфичный):
SELECT '123'::integer;
SELECT g::date;
-- Плюсы: короче, удобнее
-- Минусы: не работает в других СУБД

-- Функция CAST (стандарт ANSI SQL):
SELECT CAST('123' AS integer);
SELECT CAST(g AS date);
-- Плюсы: стандарт, работает везде
-- Минусы: более многословно

Результат одинаковый!
В задании можно использовать любой вариант.
```

