--   ...
-- )
-- 
-- Без подзапросов (статично):
-- VALUES (20, 9, 3, '2022-01-08')
-- 
-- Проблемы со статичными значениями:
-- ❌ Если MAX(id) = 25, а мы указали 20 → конфликт!
-- ❌ Если Dmitriy имеет id = 10, а мы указали 9 → ошибка!
-- ❌ Скрипт НЕ работает на другой БД (другие ID)
-- 
-- Преимущества подзапросов:
