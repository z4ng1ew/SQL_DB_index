-- ВОПРОС: Что такое COALESCE и зачем он нужен?
-- ОТВЕТ: COALESCE - функция замены NULL значением по умолчанию.
-- 
-- Синтаксис: COALESCE(значение1, значение2, ..., значениеN)
-- Возвращает ПЕРВОЕ НЕ-NULL значение из списка
-- 
-- Примеры:
-- COALESCE(NULL, 0) = 0
-- COALESCE(5, 0) = 5
-- COALESCE(NULL, NULL, 7) = 7
-- COALESCE(NULL, NULL, NULL) = NULL
-- 
-- В нашем коде:
-- COALESCE(MAX(id), 0)
-- 
-- Случай 1: Таблица НЕ пустая
-- MAX(id) = 19 → COALESCE(19, 0) = 19 → 19 + 1 = 20
-- 
-- Случай 2: Таблица пустая
-- MAX(id) = NULL → COALESCE(NULL, 0) = 0 → 0 + 1 = 1
-- 
-- Без COALESCE:
-- NULL + 1 = NULL → INSERT получит NULL → ошибка!
-- 
-- Аналогия в C:
-- int max_id = get_max_id();  // может вернуть -1 (нет данных)
-- int new_id = (max_id == -1) ? 1 : max_id + 1;
-- 
-- Аналогия в JS:
-- let maxId = getMaxId();  // может вернуть null
-- let newId = (maxId ?? 0) + 1;  // оператор ??

