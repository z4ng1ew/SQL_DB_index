### Вопрос 3: "Зачем три подзапроса вместо простых значений?"

**Ответ:**

```sql
СТАТИЧНЫЕ значения (плохо):
INSERT INTO person_visits VALUES (20, 9, 3, '2022-01-08');
                                  ↑   ↑  ↑
                                  Жёстко заданы

