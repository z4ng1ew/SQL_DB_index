### Вопрос 5: "Почему ORDER BY pizzeria.id важен?"

**Ответ:**

```sql
БЕЗ ORDER BY (недетерминированно):

SELECT pizzeria.id FROM ...
WHERE price < 800 AND pizzeria.name != 'Papa Johns'
LIMIT 1;

Результат: СЛУЧАЙНЫЙ!
Может быть:
- id=3 (DoDo Pizza)
- id=5 (Best Pizza)
- id=6 (DinoPizza)

Зависит от:
- Физического порядка строк на диске
- Планировщика PostgreSQL
- Индексов

Первый запуск: id=3
Второй запуск: id=5  ← РАЗНЫЕ результаты!
Третий запуск: id=3

Проблемы:
❌ Нестабильный результат
❌ Сложно тестировать
❌ Сложно отлаживать

───────────────────────────────────────

С ORDER BY (детерминированно):

SELECT pizzeria.id FROM ...
WHERE price < 800 AND pizzeria.name != 'Papa Johns'
ORDER BY pizzeria.id  -- ← сортировка!
LIMIT 1;

Результат: СТАБИЛЬНЫЙ!
Всегда:
- id=3 (минимальный подходящий ID)

Каждый запуск: id=3  ← ОДИНАКОВЫЙ результат!

Преимущества:
✅ Предсказуемость
✅ Повторяемость
✅ Легко тестировать
✅ Легко отлаживать

Правило:
ВСЕГДА используй ORDER BY перед LIMIT
если нужен стабильный результат!
