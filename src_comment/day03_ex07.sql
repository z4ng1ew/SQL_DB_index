❌ ID=20 может быть занят → конфликт
❌ person_id=9 может быть другим в другой БД
❌ pizzeria_id=3 тоже может отличаться
❌ Не работает на другом окружении

ДИНАМИЧЕСКИЕ подзапросы (хорошо):
INSERT INTO person_visits VALUES (
    (SELECT COALESCE(MAX(id), 0) + 1 FROM person_visits),  -- авто-ID
    (SELECT id FROM person WHERE name = 'Dmitriy'),        -- поиск по имени
    (SELECT ... ORDER BY id LIMIT 1),                      -- поиск пиццерии
    '2022-01-08'
);

Преимущества:
✅ ID вычисляется автоматически (как SERIAL)
✅ Ищет Dmitriy по имени (не зависит от конкретного ID)
✅ Находит подходящую пиццерию по условиям
✅ Работает на любой БД с такой структурой

Аналогия в программировании:

// Плохо (хардкод):
int userId = 9;
int placeId = 3;

// Хорошо (динамически):
int userId = findUserByName("Dmitriy");
int placeId = findCheapestPlace(maxPrice = 800);
