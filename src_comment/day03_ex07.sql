### Вопрос 1: "Как работает COALESCE?"

**Ответ:**

```sql
-- COALESCE = "первое НЕ-NULL значение"

-- Синтаксис:
COALESCE(значение1, значение2, значение3, ...)

-- Примеры:
COALESCE(NULL, 5) = 5
COALESCE(10, 5) = 10  -- вернёт первое (10)
COALESCE(NULL, NULL, 7) = 7
COALESCE(NULL, NULL, NULL) = NULL

-- В нашем коде:
COALESCE(MAX(id), 0)

-- Случай 1: Таблица содержит данные
MAX(id) = 19  -- не NULL
COALESCE(19, 0) = 19  -- вернёт 19
19 + 1 = 20  -- новый ID

-- Случай 2: Таблица пустая
MAX(id) = NULL  -- нет строк
COALESCE(NULL, 0) = 0  -- вернёт 0
0 + 1 = 1  -- первый ID

Аналогии:

JavaScript (оператор ??):
let result = value ?? defaultValue;
let newId = (maxId ?? 0) + 1;

C (тернарный оператор):
int result = (value != NULL) ? value : defaultValue;
int newId = (maxId != -1) ? maxId + 1 : 1;

Python (or):
result = value or default_value
new_id = (max_id or 0) + 1
```

