### Вопрос 2: "Что такое ON CONFLICT и зачем он нужен?"

**Ответ:**

```sql
ON CONFLICT - обработка конфликтов при INSERT

Конфликт = нарушение уникального ограничения

В person_visits есть:
UNIQUE (person_id, pizzeria_id, visit_date)
"Один человек не может посетить одну пиццерию дважды в день"

Сценарий конфликта:

-- Первый INSERT:
INSERT INTO person_visits VALUES (20, 9, 3, '2022-01-08');
✅ Успешно (такой записи нет)

-- Второй INSERT (запустили скрипт снова):
INSERT INTO person_visits VALUES (21, 9, 3, '2022-01-08');
❌ КОНФЛИКТ! (person_id=9, pizzeria_id=3, date=2022-01-08 уже есть)

БЕЗ ON CONFLICT:
ERROR: duplicate key value violates unique constraint "uk_person_visits"
Скрипт падает с ошибкой ❌

С ON CONFLICT DO NOTHING:
Конфликт обнаружен → INSERT пропускается → скрипт продолжается ✅

Варианты действий:

1. DO NOTHING - игнорировать
   ON CONFLICT DO NOTHING;

2. DO UPDATE - обновить существующую строку
   ON CONFLICT (person_id, pizzeria_id, visit_date)
   DO UPDATE SET ... ;

3. Без обработки - выбросить ошибку
   (по умолчанию)

Идемпотентность:
Скрипт с DO NOTHING можно запускать многократно →
результат одинаковый (нет дубликатов).
```

