### Вопрос 4: "Почему CAST к INTEGER, а не ROUND?"

**Ответ:**

```sql
CAST vs ROUND - разные операции:

-- CAST просто отбрасывает дробную часть:
CAST(720.9 AS INTEGER) = 720 (отбросили .9)
CAST(720.1 AS INTEGER) = 720 (отбросили .1)

-- ROUND округляет по математическим правилам:
ROUND(720.9) = 721 (округлили вверх)
ROUND(720.1) = 720 (округлили вниз)
ROUND(720.5) = 721 (0.5 и выше → вверх)

В нашей задаче:
price - price * 0.1 всегда даёт целые числа для целых цен!

Примеры:
800 - 80 = 720.0 → CAST → 720 ✅
1100 - 110 = 990.0 → CAST → 990 ✅
1200 - 120 = 1080.0 → CAST → 1080 ✅

Дробной части нет, поэтому:
CAST = ROUND (в данном случае)

Но задание требует INTEGER, поэтому CAST правильнее.

Если бы цены были дробными (799.99):
799.99 - 79.999 = 719.991
CAST(719.991 AS INTEGER) = 719
ROUND(719.991) = 720

В реальном магазине использовали бы ROUND.
```

