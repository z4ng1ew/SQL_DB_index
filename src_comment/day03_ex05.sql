-- SELECT - начало запроса, определяющего VIEW
-- Перечисляем колонки, которые будут в результирующем представлении
SELECT 
    -- p.name - имя человека из таблицы person
    -- p - это алиас (псевдоним) таблицы person
    -- name - VARCHAR колонка, содержит имена: "Andrey", "Anna", "Denis" и т.д.
    -- Эта колонка показывает, КТО сделал заказ
    p.name,
    
