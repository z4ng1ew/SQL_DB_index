## 🎯 Когда использовать CAST?

### 1️⃣ **Приведение к нужному формату**

```sql
-- Задание требует INTEGER:
SELECT CAST(price * 0.9 AS INTEGER) AS discount_price;
-- Без CAST был бы NUMERIC: 720.0
-- С CAST стало INTEGER: 720
```

---

### 2️⃣ **Математические операции**

```sql
-- Деление с дробной частью:
SELECT 10 / 3;  -- Результат: 3 (целочисленное деление!)

SELECT CAST(10 AS NUMERIC) / 3;  -- Результат: 3.333...
-- или
SELECT 10::NUMERIC / 3;
```

---

### 3️⃣ **Работа с датами**

```sql
-- Строка → дата для вычислений:
SELECT CAST('2022-01-15' AS DATE) + INTERVAL '7 days';
-- Результат: 2022-01-22

-- Дата → строка для форматирования:
SELECT CAST(NOW() AS VARCHAR);
```

---

### 4️⃣ **Сравнение разных типов**

```sql
-- Сравнение строки с числом:
SELECT * FROM products WHERE price > CAST('100' AS INTEGER);
--                                          ↑
--                                    строка → число
```

---

### 5️⃣ **Конкатенация строк**

```sql
-- Число + строка:
SELECT 'Order #' || CAST(order_id AS VARCHAR) FROM orders;
-- Результат: 'Order #123', 'Order #456', ...
```

