## ⚠️ CAST vs другие функции

### CAST vs ROUND:

```sql
-- CAST просто отбрасывает:
SELECT CAST(3.9 AS INTEGER);  -- 3 (отбросили .9)
SELECT CAST(3.1 AS INTEGER);  -- 3 (отбросили .1)

-- ROUND округляет:
SELECT ROUND(3.9);  -- 4 (округлили вверх)
SELECT ROUND(3.1);  -- 3 (округлили вниз)
SELECT ROUND(3.5);  -- 4 (0.5 и выше → вверх)
```

---

### CAST vs FLOOR / CEIL:

```sql
-- FLOOR (округление вниз):
SELECT FLOOR(3.9);  -- 3
SELECT FLOOR(3.1);  -- 3

-- CEIL (округление вверх):
SELECT CEIL(3.1);   -- 4
SELECT CEIL(3.9);   -- 4

-- CAST (отбрасывание):
SELECT CAST(3.9 AS INTEGER);  -- 3 (= FLOOR для положительных)
SELECT CAST(-3.9 AS INTEGER); -- -3 (= CEIL для отрицательных)
```

---

### CAST vs TRUNC:

```sql
-- TRUNC (отбрасывание дробной части):
SELECT TRUNC(3.9);  -- 3
SELECT TRUNC(3.1);  -- 3

-- CAST к INTEGER делает то же:
SELECT CAST(3.9 AS INTEGER);  -- 3

-- Разница в типах:
-- TRUNC возвращает NUMERIC
-- CAST возвращает INTEGER
```

---

## 🔍 PostgreSQL :: vs CAST

### Два способа приведения типов:

```sql
-- Способ 1: CAST (стандарт ANSI SQL)
SELECT CAST(value AS type);

-- Способ 2: :: (PostgreSQL-специфичный)
SELECT value::type;
```

### Сравнение:

| Аспект | CAST | :: |
|--------|------|----|
| **Стандарт** | ✅ ANSI SQL (работает везде) | ❌ Только PostgreSQL |
| **Читаемость** | ✅ Явно показывает преобразование | ⚠️ Может быть не очевидно |
| **Длина** | ❌ Длиннее | ✅ Короче |
| **Портируемость** | ✅ MySQL, Oracle, MS SQL | ❌ Только PostgreSQL |

### Примеры эквивалентности:

```sql
-- Одинаковые результаты:
CAST(123 AS VARCHAR)     =  123::VARCHAR
CAST('456' AS INTEGER)   =  '456'::INTEGER
CAST(NOW() AS DATE)      =  NOW()::DATE
CAST(price * 0.9 AS INT) =  (price * 0.9)::INT
```

**Рекомендация:** Используй **CAST** для переносимости, **::** для краткости в PostgreSQL.

