-- ВОПРОС: Почему используется CAST, а не просто вычисление?
-- ОТВЕТ: Без CAST результат имеет тип NUMERIC (с дробной частью).
-- 
-- Без CAST:
-- SELECT m.price - m.price * 0.1 FROM menu WHERE id=8;
-- Результат: 720.0 (тип NUMERIC)
-- 
-- С CAST:
-- SELECT CAST(m.price - m.price * 0.1 AS INTEGER) FROM menu WHERE id=8;
-- Результат: 720 (тип INTEGER)
-- 
-- Задание требует: "приведи столбец discount_price к целочисленному типу"

-- ВОПРОС: Чем CAST отличается от оператора ::?
-- ОТВЕТ: Это два способа приведения типов в PostgreSQL.
-- 
-- CAST (стандарт ANSI SQL):
-- CAST(value AS type)
-- Работает во всех СУБД
-- 
-- :: (оператор PostgreSQL):
-- value::type
-- Только PostgreSQL, короче
-- 
-- Примеры:
-- CAST(720.5 AS INTEGER) = 720
-- 720.5::INTEGER = 720
-- 
-- Результат одинаковый!
-- В задании можно использовать любой вариант.

-- ВОПРОС: Почему формула price - price * 0.1, а не price * 0.9?
-- ОТВЕТ: Обе формулы дают одинаковый результат.
-- 
-- Вариант 1 (в коде):
-- price - price * 0.1
-- "Цена минус 10% скидки"
-- 800 - 80 = 720
-- 
-- Вариант 2 (альтернатива):
-- price * 0.9
-- "90% от цены"
-- 800 * 0.9 = 720
-- 
-- Первый вариант более наглядно показывает:
-- - Базовую цену (price)
-- - Размер скидки (price * 0.1 = 10%)
-- - Операцию вычитания

-- ВОПРОС: Что такое JOIN и зачем он нужен?
-- ОТВЕТ: JOIN объединяет строки из нескольких таблиц по условию.
-- 
-- Без JOIN (данные разрознены):
-- person_order: person_id=2, menu_id=8
-- ❓ Кто это? Что заказал? По какой цене?
-- 
-- С JOIN (данные объединены):
-- person_order JOIN person: person_id=2 → name='Andrey'
-- person_order JOIN menu: menu_id=8 → pizza_name='cheese pizza', price=800
-- ✅ Andrey заказал cheese pizza за 800₽
-- 
-- Типы JOIN:
-- - INNER JOIN (просто JOIN): только совпадения
-- - LEFT JOIN: все из левой таблицы + совпадения справа
-- - RIGHT JOIN: все из правой таблицы + совпадения слева
-- - FULL JOIN: все из обеих таблиц

-- ВОПРОС: Почему начинаем с person_order, а не с person?
-- ОТВЕТ: person_order - это центральная таблица (fact table).
-- 
-- Логика:
-- - person_order содержит ЗАКАЗЫ (события)
-- - person и menu - справочники (dimension tables)
-- - Мы хотим видеть ВСЕ ЗАКАЗЫ с информацией о клиенте и пицце
-- 
-- Если начать с person:
-- SELECT * FROM person JOIN person_order ...
-- → Получим всех людей, но только тех, кто делал заказы
-- → Потеряем людей БЕЗ заказов (но они нам и не нужны в этом VIEW)
-- 
-- Начиная с person_order:
-- → Получаем каждый заказ
-- → Для каждого заказа находим клиента и пиццу
-- → Это именно то, что нужно!

-- ВОПРОС: Можно ли изменить порядок JOIN?
-- ОТВЕТ: Да, порядок JOIN не влияет на результат (при INNER JOIN).
-- 
-- Вариант 1 (как в коде):
-- FROM person_order
-- JOIN person ON ...
-- JOIN menu ON ...
-- 
-- Вариант 2 (другой порядок):
-- FROM person_order
-- JOIN menu ON ...
-- JOIN person ON ...
-- 
-- Результат одинаковый!
-- Но логичнее сначала person (кто), потом menu (что).

-- ВОПРОС: Что будет, если в person_order есть menu_id, которого нет в menu?
-- ОТВЕТ: Такая строка НЕ попадёт в результат (из-за INNER JOIN).
-- 
-- INNER JOIN включает только строки с совпадениями в ОБЕИХ таблицах.
-- 
-- Но в реальной БД этого быть не должно:
-- - foreign key constraint: person_order.menu_id → menu.id
-- - Нельзя вставить menu_id, которого нет в menu
-- - PostgreSQL вернёт ошибку при попытке

-- ВОПРОС: Сколько строк вернёт VIEW?
-- ОТВЕТ: По количеству заказов в person_order.
-- 
-- Расчёт:
-- - Каждая строка в person_order = один заказ
-- - JOIN 1:1 с person (один заказ → один человек)
-- - JOIN 1:1 с menu (один заказ → одна пицца)
-- - Результат: столько же строк, сколько в person_order
-- 
-- В тестовых данных model.sql:
-- person_order содержит 20 заказов
-- → VIEW вернёт 22 строки (с учётом данных из Day 03)

-- ВОПРОС: Можно ли фильтровать VIEW?
-- ОТВЕТ: Да! VIEW можно использовать как обычную таблицу.
-- 
-- Примеры:
-- SELECT * FROM v_price_with_discount WHERE name = 'Andrey';
-- SELECT * FROM v_price_with_discount WHERE price > 1000;
-- SELECT * FROM v_price_with_discount WHERE discount_price < 700;
