    -- CAST - стандартная SQL-функция для преобразования типов
    -- AS INTEGER - указывает целевой тип данных (целое число)
    -- 
    -- Внутри CAST вычисляется цена со скидкой:
    CAST(
        -- m.price - m.price * 0.1 - формула расчёта скидки 10%
        -- 
        -- Разбор формулы:
        -- m.price * 0.1 - вычисляем 10% от цены (размер скидки)
        -- m.price - (m.price * 0.1) - вычитаем скидку из цены
        -- 
        -- Альтернативная формула (эквивалентна):
        -- m.price * 0.9 - умножаем на 0.9 (90% от цены)
