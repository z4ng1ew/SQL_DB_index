# 🔄 CAST - команда приведения типов

## 📝 Что такое CAST?

**CAST** = **преобразование (приведение) типа данных**

**Расшифровка слова:**
- **CAST** (английский) = "отливать", "формовать", "преобразовывать"
- В программировании: **type casting** = приведение типа

---

## 🎯 Простое определение

**CAST** преобразует значение из одного типа данных в другой.

```sql
CAST(значение AS новый_тип)
     ↑           ↑
  что            во что
  преобразуем    преобразуем
```

---

## 💡 Аналогия из жизни

**CAST = переливание воды в другую ёмкость**

```
Было: вода в бутылке 🍾 (тип: bottle)
       ↓ CAST
Стало: вода в стакане 🥤 (тип: glass)

Вода та же, но форма другая!
```

**В программировании:**

```
Было: 3.14 (тип: FLOAT/NUMERIC)
       ↓ CAST
Стало: 3 (тип: INTEGER)

Значение изменилось (отбросили дробь), тип изменился
```

---

## 🔧 Синтаксис

### Стандартный SQL (работает везде):

```sql
CAST(выражение AS тип_данных)
```

**Компоненты:**
- **CAST** - ключевое слово (команда)
- **выражение** - что преобразуем (значение, колонка, вычисление)
- **AS** - ключевое слово ("как", "в")
- **тип_данных** - целевой тип (INTEGER, VARCHAR, DATE, и т.д.)

---

### PostgreSQL-специфичный синтаксис:

```sql
выражение::тип_данных
```

**Это синтаксический сахар** (короче, но только в PostgreSQL)

---

## 📊 Примеры CAST

### Пример 1: Число → Целое число

```sql
-- Дробное число → целое
SELECT CAST(3.7 AS INTEGER);
-- Результат: 3 (дробная часть отбрасывается)

SELECT CAST(9.9 AS INTEGER);
-- Результат: 9 (не округляется, просто отбрасывается!)

-- PostgreSQL-синтаксис:
SELECT 3.7::INTEGER;
-- Результат: 3
```

---

### Пример 2: Текст → Число

```sql
-- Строка → число
SELECT CAST('123' AS INTEGER);
-- Результат: 123 (тип INTEGER, а не VARCHAR)

SELECT CAST('45.67' AS NUMERIC);
-- Результат: 45.67 (тип NUMERIC)

-- Ошибка при невалидном значении:
SELECT CAST('abc' AS INTEGER);
-- ERROR: invalid input syntax for type integer: "abc"
```

---

### Пример 3: Число → Текст

```sql
-- Число → строка
SELECT CAST(123 AS VARCHAR);
-- Результат: '123' (тип VARCHAR, а не INTEGER)

SELECT CAST(3.14 AS TEXT);
-- Результат: '3.14' (тип TEXT)
```

---

### Пример 4: Строка → Дата

```sql
-- Строка → дата
SELECT CAST('2022-01-15' AS DATE);
-- Результат: 2022-01-15 (тип DATE)

SELECT CAST('2022-01-15 14:30:00' AS TIMESTAMP);
-- Результат: 2022-01-15 14:30:00 (тип TIMESTAMP)
```

---

### Пример 5: Вычисление → Целое

```sql
-- Наш пример из задания:
SELECT CAST(800 - 800 * 0.1 AS INTEGER);
--           └─────────────┘
--              720.0 (NUMERIC)
-- Результат: 720 (INTEGER)

SELECT CAST(1100 * 0.9 AS INTEGER);
-- Результат: 990
```

