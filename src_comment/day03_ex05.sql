## 🔄 Аналогия в C (ты знаешь C!)

### В языке C:

```c
// Приведение типов в C:
float x = 3.7;
int y = (int)x;  // y = 3 (дробная часть отбрасывается)

double pi = 3.14159;
int rounded = (int)pi;  // rounded = 3

char str[] = "123";
