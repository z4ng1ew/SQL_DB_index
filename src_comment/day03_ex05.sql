        -- Примеры расчёта:
        -- Цена 800: 800 - 800*0.1 = 800 - 80 = 720
        -- Цена 1100: 1100 - 1100*0.1 = 1100 - 110 = 990
        -- Цена 1200: 1200 - 1200*0.1 = 1200 - 120 = 1080
        m.price - m.price * 0.1 
        
        -- AS INTEGER - приведение результата к типу INTEGER
        -- Это требование задания: "приведи столбец discount_price к целочисленному типу"
        -- 
        -- Зачем нужно CAST:
        -- - m.price имеет тип NUMERIC
        -- - Результат вычисления (price - price*0.1) также NUMERIC
        -- - NUMERIC может иметь дробную часть: 720.0, 990.0
        -- - INTEGER отбрасывает дробную часть: 720, 990
        -- 
        -- Альтернативный синтаксис (PostgreSQL):
        -- (m.price - m.price * 0.1)::INTEGER
        AS INTEGER
    ) 
    -- AS discount_price - называем вычисляемую колонку
