### Вопрос 5: "Где применяется ORDER BY - до или после UNION?"

**Ответ:**
```sql
-- ❌ НЕПРАВИЛЬНО - ORDER BY в каждой части:
(SELECT name FROM v_persons_female ORDER BY name)
UNION
(SELECT name FROM v_persons_male ORDER BY name);
-- Промежуточная сортировка потеряется после UNION!

-- ✅ ПРАВИЛЬНО - ORDER BY в конце:
SELECT name FROM v_persons_female
UNION
SELECT name FROM v_persons_male
ORDER BY name;
-- Сортируется ИТОГОВЫЙ результат после объединения
```

**Визуально:**
```
Шаг 1: SELECT из v_persons_female → Anna, Kate, Elvira, Irina, Nataly
Шаг 2: SELECT из v_persons_male → Andrey, Denis, Peter, Dmitriy
Шаг 3: UNION объединяет → все 9 имён (неупорядоченно)
Шаг 4: ORDER BY сортирует → Andrey, Anna, Denis, ...
```

