### Ключевые операторы:

| Оператор | Назначение | Особенность |
|----------|------------|-------------|
| **UNION** | Объединение строк | Удаляет дубликаты |
| **UNION ALL** | Объединение строк | Оставляет дубликаты |
| **ORDER BY 1** | Сортировка | По первой колонке |

