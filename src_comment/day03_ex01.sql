**Небольшой совет для уровня Junior+:**
Так как вы знаете C и Python, вам будет полезно знать, что `UNION` по умолчанию удаляет дубликаты (работает как `DISTINCT`), что может быть дорого по производительности. Если вам нужны все записи подряд (даже полные тёзки), лучше использовать `UNION ALL` — это быстрее, так как не требует сортировки для удаления дублей.

Также `ORDER BY 1` ссылается на первую колонку (`name`). Для читаемости кода лучше явно указывать имя колонки: `ORDER BY name`.

Для удобного копирования вот обычная версия в блоке кода:

```sql
SELECT name
FROM v_persons_female
UNION
SELECT name
FROM v_persons_male
ORDER BY name;
