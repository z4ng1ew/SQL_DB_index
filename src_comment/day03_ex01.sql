## 🎓 Дополнительные вопросы для защиты

### Вопрос 1: "Чем UNION отличается от UNION ALL?"

**Ответ:**
```sql
-- UNION - удаляет дубликаты (медленнее)
SELECT name FROM v_persons_female  -- Anna, Kate
UNION
SELECT name FROM v_persons_male;   -- Anna, Bob

-- Результат: Anna, Kate, Bob (Anna только один раз)

-- UNION ALL - оставляет все строки, включая дубликаты (быстрее)
SELECT name FROM v_persons_female  -- Anna, Kate
UNION ALL
SELECT name FROM v_persons_male;   -- Anna, Bob

-- Результат: Anna, Kate, Anna, Bob (Anna дважды)
```

**В нашем случае:** Дубликатов нет (gender разный), поэтому результат одинаковый.

---

### Вопрос 2: "Можно ли сделать JOIN вместо UNION?"

**Ответ:**
```
❌ НЕЛЬЗЯ использовать JOIN для этой задачи!

JOIN - объединяет КОЛОНКИ (горизонтально):
SELECT * FROM table1 JOIN table2
→ Результат: все колонки из table1 + все колонки из table2

UNION - объединяет СТРОКИ (вертикально):
SELECT * FROM table1 UNION SELECT * FROM table2
→ Результат: строки из table1, затем строки из table2

Нам нужно объединить СТРОКИ (список людей), поэтому UNION.
```

