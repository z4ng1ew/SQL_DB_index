## 🎓 Дополнительные вопросы для защиты

### Вопрос 1: "Что такое симметричная разность?"

**Ответ:**

```
Симметричная разность (symmetric difference) - операция теории множеств.

Формула: A △ B = (A − B) ∪ (B − A)

Простыми словами:
"Элементы, которые есть ЛИБО в A, ЛИБО в B, но НЕ в обоих"

Примеры:
• {1, 2, 3} △ {2, 3, 4} = {1, 4}
  (1 только в первом, 4 только во втором, 2 и 3 в обоих - исключаем)

• Люди на вечеринке:
  Понедельник: {Анна, Боб, Катя}
  Вторник: {Боб, Катя, Денис}
  △ = {Анна, Денис} (они были только в один день)

Диаграмма Венна:
  ┌─────────┐
  │ Только A│   ┌──────────┐
  │    1    │2,3│ Только B │
  └─────────┘   │    4     │
                └──────────┘
     ↑                ↑
  Включаем      Включаем
  
  Пересечение (2,3) НЕ включаем!

В SQL: (A EXCEPT B) UNION (B EXCEPT A)
```

---

### Вопрос 2: "Зачем две части формулы?"

**Ответ:**

```
Почему не просто (R − S) или (S − R)?

Рассмотрим пример:
R (2 января): {Анна, Боб, Катя}
S (6 января): {Боб, Катя, Денис}

Только (R − S):
{Анна, Боб, Катя} − {Боб, Катя, Денис} = {Анна}
❌ Потеряли Дениса (он был 6-го, но не 2-го)!

Только (S − R):
{Боб, Катя, Денис} − {Анна, Боб, Катя} = {Денис}
❌ Потеряли Анну (она была 2-го, но не 6-го)!

(R − S) ∪ (S − R):
{Анна} ∪ {Денис} = {Анна, Денис}
✅ Получили всех, кто был ТОЛЬКО в один день!

Боб и Катя были ОБА дня → исключены обоими EXCEPT.
Анна и Денис были ОДИН день → включены через UNION.
```

