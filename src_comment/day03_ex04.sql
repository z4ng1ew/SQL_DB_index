-- =============================================================================
-- ПЕРВАЯ ЧАСТЬ: (R − S) = "Были 2-го, но НЕ были 6-го"
-- =============================================================================

-- Открывающая скобка для группировки первой части формулы
-- Важно для правильного порядка операций: сначала EXCEPT, потом UNION
-- Без скобок UNION и EXCEPT могут неправильно сгруппироваться
(
    -- SELECT person_id - выбираем идентификаторы людей
    -- Нужны только ID, а не полная информация о визитах
    -- person_id - внешний ключ на таблицу person
    SELECT person_id
    
    -- FROM person_visits - таблица с записями о посещениях пиццерий
    -- Структура: id, person_id, pizzeria_id, visit_date
    FROM person_visits
    
    -- WHERE visit_date = '2022-01-02' - фильтр по дате
    -- Выбираем только визиты 2 января 2022 года
    -- '2022-01-02' - строковый литерал в формате ISO 8601 (YYYY-MM-DD)
    -- PostgreSQL автоматически преобразует в тип DATE
    -- Это множество R в формуле
    WHERE visit_date = '2022-01-02'
    
    -- EXCEPT - оператор разности множеств (вычитание)
    -- Математическая запись: R \ S (R минус S)
    -- Удаляет из первого множества все элементы второго множества
    -- Автоматически убирает дубликаты
    -- 
    -- Логика: из всех, кто был 2-го, вычитаем тех, кто был 6-го
    -- Результат: те, кто был 2-го, но НЕ был 6-го
