    FROM person_visits
    
    -- WHERE visit_date = '2022-01-06' - фильтр по другой дате
    -- Выбираем только визиты 6 января 2022 года
    -- Это множество S в формуле
    WHERE visit_date = '2022-01-06'
)
-- Закрывающая скобка первой части: (R − S)

-- =============================================================================
-- Оператор объединения множеств
-- =============================================================================

-- UNION - объединяет результаты двух запросов
-- Математическая запись: ∪ (знак объединения)
-- Автоматически удаляет дубликаты
-- 
-- Альтернативы:
-- - UNION ALL: оставляет дубликаты (быстрее, но нам не нужно)
-- - UNION DISTINCT: явно указывает удаление дубликатов (по умолчанию)
-- 
-- В нашем случае дубликатов быть не может, так как:
-- (R − S) и (S − R) - непересекающиеся множества по определению
-- Если person_id есть в первой части, его не может быть во второй
UNION

-- =============================================================================
-- ВТОРАЯ ЧАСТЬ: (S − R) = "Были 6-го, но НЕ были 2-го"
-- =============================================================================

-- Открывающая скобка для второй части формулы
(
    -- SELECT person_id - выбираем ID людей, которые были 6-го
    SELECT person_id
    
    -- FROM person_visits - та же таблица
    FROM person_visits
    
    -- WHERE visit_date = '2022-01-06' - фильтр: только 6 января
    -- Это множество S (сейчас оно первое в операции вычитания)
    WHERE visit_date = '2022-01-06'
    
    -- EXCEPT - вычитаем множество R из множества S
    -- Логика: из всех, кто был 6-го, вычитаем тех, кто был 2-го
    -- Результат: те, кто был 6-го, но НЕ был 2-го
    EXCEPT
    
    -- SELECT person_id - выбираем ID людей, которые были 2-го
    SELECT person_id
    
    -- FROM person_visits - та же таблица
    FROM person_visits
    
    -- WHERE visit_date = '2022-01-02' - фильтр: только 2 января
    -- Это множество R (сейчас оно второе в операции вычитания)
    WHERE visit_date = '2022-01-02'
)
-- Закрывающая скобка второй части: (S − R)

-- Точка с запятой завершает определение VIEW
;

-- =============================================================================
-- ИТОГОВАЯ ФОРМУЛА: (R − S) ∪ (S − R)
-- =============================================================================
-- Это СИММЕТРИЧНАЯ РАЗНОСТЬ (symmetric difference)
-- Математическая запись: R △ S или R ⊕ S
-- 
-- Результат: элементы, которые принадлежат ЛИБО R, ЛИБО S, но НЕ обоим сразу
-- 
-- В нашем случае:
-- - Люди, которые были 2-го, но не 6-го  ← первая часть
--   ПЛЮС
-- - Люди, которые были 6-го, но не 2-го  ← вторая часть
-- 
-- НЕ включаются:
-- - Люди, которые были И 2-го, И 6-го (их вычли оба EXCEPT)
-- - Люди, которые не были ни 2-го, ни 6-го (их нет в обоих множествах)


-- =============================================================================
-- ПРОВЕРКА РЕЗУЛЬТАТА
-- =============================================================================

-- SELECT * - выбираем все колонки из VIEW
-- В VIEW только одна колонка: person_id (тип BIGINT)
SELECT * 

-- FROM v_symmetric_union - наш созданный VIEW
-- VIEW работает как обычная таблица - можем к нему делать SELECT
FROM v_symmetric_union 

-- ORDER BY person_id - сортируем результат по возрастанию ID
-- Альтернативный синтаксис: ORDER BY 1 (по первой колонке)
-- Сортировка делает результат предсказуемым и читаемым
-- Важно для проверки соответствия с ожидаемым результатом
ORDER BY person_id;


