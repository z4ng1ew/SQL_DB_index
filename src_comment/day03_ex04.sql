### Вопрос 3: "Можно ли использовать XOR вместо симметричной разности?"

**Ответ:**

```
В теории множеств симметричная разность аналогична XOR (исключающее ИЛИ).

Логическая таблица (для одного элемента):
┌───────┬───────┬────────────────────┐
│ В R?  │ В S?  │ В результате?      │
├───────┼───────┼────────────────────┤
│ Нет   │ Нет   │ Нет   (0 XOR 0=0) │
│ Да    │ Нет   │ ДА!   (1 XOR 0=1) │
│ Нет   │ Да    │ ДА!   (0 XOR 1=1) │
│ Да    │ Да    │ Нет   (1 XOR 1=0) │
└───────┴───────┴────────────────────┘

SQL не имеет оператора XOR для множеств,
но формула (A − B) ∪ (B − A) реализует ту же логику!

В программировании:
JavaScript: array1.filter(x => !array2.includes(x))
            .concat(array2.filter(x => !array1.includes(x)))

Python: set1.symmetric_difference(set2)
        или: set1 ^ set2 (оператор XOR)

SQL: (SELECT FROM set1 EXCEPT SELECT FROM set2)
     UNION
     (SELECT FROM set2 EXCEPT SELECT FROM set1)
```

