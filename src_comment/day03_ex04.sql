## 🧮 Что делает этот VIEW? (Теория множеств)

### Формула: (R − S) ∪ (S − R)

**Это СИММЕТРИЧНАЯ РАЗНОСТЬ (symmetric difference)**

**Расшифровка:**
- **R** = множество person_id, которые были 2 января
- **S** = множество person_id, которые были 6 января
- **R − S** = те, кто был 2-го, но НЕ был 6-го
- **S − R** = те, кто был 6-го, но НЕ был 2-го
- **(R − S) ∪ (S − R)** = объединение обеих групп

---

### 🍕 Аналогия с пиццерией:

```
2 января пришли:  Анна, Боб, Катя
6 января пришли:  Боб, Денис

R − S (были 2-го, но не 6-го):  Анна, Катя
S − R (были 6-го, но не 2-го):  Денис

Симметричная разность:  Анна, Катя, Денис
(все, кто был ЛИБО 2-го, ЛИБО 6-го, но НЕ в оба дня)
```

**Боб не попал** - он был ОБА дня!

