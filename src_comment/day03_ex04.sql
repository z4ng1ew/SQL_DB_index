### Вопрос 4: "Почему важен порядок скобок?"

**Ответ:**

```sql
-- ❌ БЕЗ СКОБОК (неоднозначно):
SELECT ... 
EXCEPT SELECT ... 
UNION SELECT ... 
EXCEPT SELECT ...

PostgreSQL выполнит слева направо:
((A EXCEPT B) UNION C) EXCEPT D
↑ Это НЕ то, что нужно!

-- ✅ СО СКОБКАМИ (ясно):
(SELECT ... EXCEPT SELECT ...)
UNION
(SELECT ... EXCEPT SELECT ...)

PostgreSQL выполнит:
(A EXCEPT B) UNION (C EXCEPT D)
↑ Это правильная формула симметричной разности!

Аналогия из математики:
2 - 3 + 4 - 5 = ?
Без скобок: ((2-3)+4)-5 = -2
С скобками: (2-3) + (4-5) = -2 (тот же результат)

Но для логики важна ясность!
```

