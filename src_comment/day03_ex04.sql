UNION объединяет обе части.

Результат: люди, которые были ТОЛЬКО в один из этих дней,
но не в оба сразу.

Скобки важны для правильного порядка операций: 
сначала вычисляем обе разности, затем объединяем.

По тестовым данным: person_id 2 и 8 (Andrey и Nataly).
Те, кто был оба дня, НЕ попадут в результат.
```

