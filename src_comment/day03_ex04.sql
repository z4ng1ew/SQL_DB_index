## 🔍 Разбор SQL-операторов

### 1. `EXCEPT` - разность множеств

**Синтаксис:**
```sql
SELECT ... 
EXCEPT 
SELECT ...
```

**Что делает:** Возвращает строки из первого SELECT, которых НЕТ во втором

**Расшифровка:** **EXCEPT** = "исключая", "кроме"

**Пример:**

```sql
-- Все люди:
SELECT person_id FROM person_visits WHERE visit_date = '2022-01-02';
-- Результат: 1, 2, 3

-- Минус те, кто был 6-го:
SELECT person_id FROM person_visits WHERE visit_date = '2022-01-02'
EXCEPT
SELECT person_id FROM person_visits WHERE visit_date = '2022-01-06';
-- Результат: 1, 3  (убрали 2, потому что он был и 6-го)
```

**На JavaScript:**

```javascript
// EXCEPT = filter + includes
const day2 = [1, 2, 3];
const day6 = [2, 4];

const result = day2.filter(id => !day6.includes(id));
// result = [1, 3]
```

**На C (аналогия):**

```c
// Разность множеств:
int day2[] = {1, 2, 3};
int day6[] = {2, 4};

// Результат: элементы из day2, которых нет в day6
// {1, 3}
```

---

### 2. `UNION` - объединение множеств

**Синтаксис:**
```sql
SELECT ... 
UNION 
SELECT ...
```

**Что делает:** Объединяет результаты двух SELECT, **убирая дубликаты**

**Расшифровка:** **UNION** = "объединение", "союз"

**Пример:**

```sql
-- Первая группа:
SELECT person_id FROM ... WHERE ...;  -- Результат: 1, 3

-- Вторая группа:
SELECT person_id FROM ... WHERE ...;  -- Результат: 4

-- Объединение:
(первая группа) UNION (вторая группа);
-- Результат: 1, 3, 4
```

**На JavaScript:**

```javascript
// UNION = [...new Set([...arr1, ...arr2])]
const group1 = [1, 3];
const group2 = [4];

const result = [...new Set([...group1, ...group2])];
// result = [1, 3, 4]
```

