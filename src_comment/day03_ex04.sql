-- ВОПРОС: Что такое симметричная разность?
-- ОТВЕТ: Это операция теории множеств, которая возвращает элементы,
--        принадлежащие ТОЛЬКО одному из множеств, но не обоим.
-- 
-- Формула: A △ B = (A − B) ∪ (B − A)
-- 
-- Примеры:
-- {1, 2, 3} △ {2, 3, 4} = {1, 4}
-- {Anna, Bob} △ {Bob, Kate} = {Anna, Kate}
-- 
-- Диаграмма Венна:
--     A         B
--   ┌───┐     ┌───┐
--   │ 1 │2,3│ 4 │
--   └───┘     └───┘
--     ↑         ↑
--   Только    Только
--   в A       в B
-- 
-- Симметричная разность = закрашенные области (1 и 4)

-- ВОПРОС: Почему нужны скобки вокруг EXCEPT?
-- ОТВЕТ: Для правильного порядка выполнения операций.
-- 
-- БЕЗ скобок:
-- SELECT ... EXCEPT SELECT ... UNION SELECT ... EXCEPT SELECT ...
-- ↑ Неоднозначно! Какая операция первая?
-- 
-- СО скобками:
-- (SELECT ... EXCEPT SELECT ...) UNION (SELECT ... EXCEPT SELECT ...)
-- ↑ Ясно: сначала два EXCEPT, потом UNION результатов
-- 
-- Скобки гарантируют:
-- 1. Сначала вычисляем (R − S)
-- 2. Затем вычисляем (S − R)
-- 3. Потом объединяем результаты через UNION

-- ВОПРОС: Можно ли упростить запрос?
-- ОТВЕТ: Технически можно использовать FULL OUTER JOIN, но сложнее:
-- 
-- SELECT COALESCE(r.person_id, s.person_id)
-- FROM (SELECT DISTINCT person_id FROM person_visits 
--       WHERE visit_date = '2022-01-02') r
-- FULL OUTER JOIN 
--      (SELECT DISTINCT person_id FROM person_visits 
--       WHERE visit_date = '2022-01-06') s
-- ON r.person_id = s.person_id
-- WHERE r.person_id IS NULL OR s.person_id IS NULL;
-- 
-- Но формула (R − S) ∪ (S − R) гораздо понятнее!

-- ВОПРОС: Зачем нужна симметричная разность в реальной жизни?
-- ОТВЕТ: Примеры использования:
-- 
-- 1. Аналитика изменений:
--    Кто перестал посещать? Кто начал посещать?
-- 
-- 2. A/B тестирование:
--    Пользователи ТОЛЬКО в группе A или ТОЛЬКО в группе B
-- 
-- 3. Сравнение списков:
--    Какие элементы различаются между двумя версиями?
-- 
-- 4. Поиск аномалий:
--    Клиенты, которые изменили поведение

-- ВОПРОС: Почему в задании написано "определения не существует"?
-- ОТВЕТ: В тексте задания сказано:
--        "(*) Honestly, there is no such definition as 'symmetric union' in set theory."
-- 
-- Это авторская интерпретация. Правильное название:
-- - SYMMETRIC DIFFERENCE (симметричная РАЗНОСТЬ)
-- - Обозначение: △ или ⊕
-- 
-- Но автор назвал VIEW "symmetric_union", потому что:
-- - В формуле используется UNION
-- - Название более понятное для студентов

-- ВОПРОС: Какой будет результат на тестовых данных?
-- ОТВЕТ: По данным model.sql:
-- 
-- Посещения 2022-01-02:
-- - person_id = 2 (Andrey)
-- 
-- Посещения 2022-01-06:
-- - person_id = 8 (Nataly)
-- 
-- (R − S): {2} − {} = {2}  ← Andrey был 2-го, не был 6-го
-- (S − R): {8} − {} = {8}  ← Nataly была 6-го, не была 2-го
-- 
-- UNION: {2} ∪ {8} = {2, 8}
-- 
-- Результат: person_id = 2, 8
-- 
-- Если кто-то был ОБА дня - его ID НЕ попадёт в результат!

-- ВОПРОС: Что будет, если использовать UNION ALL вместо UNION?
-- ОТВЕТ: Результат не изменится в данном случае.
-- 
-- Причина: (R − S) и (S − R) не пересекаются по определению.
-- 
-- Если person_id есть в первой части (был 2-го, не был 6-го),
-- то его НЕ может быть во второй части (был 6-го, не был 2-го).
-- 
-- Дубликатов не будет, поэтому:
-- UNION = UNION ALL (в этом конкретном случае)
-- 
-- Но UNION безопаснее и показывает намерение убрать дубликаты.

-- =============================================================================
